import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve,dirname} from 'node:path';
import assert from 'node:assert/strict';
import {loadModel} from '../../../../../packages/cli/dist/model.js';
import {replayScenario} from '../../../../../packages/session/dist/index.js';
const B=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const loaded=loadModel(B+'/materials/expense.shitae');
const prepared={...loaded,files:loaded.modulePaths};
const initial=JSON.parse(readFileSync(B+'/materials/loaded.scenario.json'));
const s=await replayScenario(prepared,initial);
const history=s.query({select:['history'],history:{limit:100}}).data.history;assert.equal(history.nextAfter,null);
const labels=['','下書きを作る','金額を入力する','領収書を確認する','申請する','差し戻す','金額を訂正する','再申請する','承認する','保存する','支払いを予約する','領収書の更新を受け取る','支払いを完了する'];
const conditions={4:'提出',5:'領収書不足',7:'修正済み',8:'問題なし',9:'成功'};
const rows=[];
for(const o of history.items.filter(o=>o.operationId>0)){
 const view=s.query({select:['observation'],observationId:o.id}).data.observation.view;
 const values=Object.fromEntries(view.state.sharedVariants.map(x=>[x.component,x.variant]));
 rows.push({step:o.operationId,result:o.resultIndex+1,id:o.id,title:labels[o.operationId],condition:conditions[o.operationId]||'指定なし',effect:o.label,values});
}
assert.equal(rows.find(x=>x.step===2).values['申請額'],'一万二千円');
assert.equal(rows.find(x=>x.step===6).values['申請額'],'一万円');
assert.equal(rows.at(-1).values['文書B'],'再確認が必要');
const point=rows.find(x=>x.step===7&&x.result===1);
s.seek(point.id);
const resumed=await s.exportScenario();
writeFileSync(B+'/materials/resumed.scenario.json',JSON.stringify(resumed,null,2)+'\n');
assert.equal(s.query({select:['state']}).data.state.sharedVariants.find(x=>x.component==='文書B').variant,'確認済み');
const act=name=>{const a=s.query({select:['actions']}).data.actions.items.find(x=>x.actionText===name);return s.dispatch({handle:a.handle})};
const before=s.query().summary;
const noOp=act('前の画面に戻る');assert.equal(s.query().summary.cursorObservationId,before.cursorObservationId);
writeFileSync(B+'/materials/noop.scenario.json',JSON.stringify(await s.exportScenario(),null,2)+'\n');
act('申請を取り下げる');
writeFileSync(B+'/materials/branched.scenario.json',JSON.stringify(await s.exportScenario(),null,2)+'\n');
const data={metadata:loaded.metadata,rows,noOpReceipt:noOp.receipt,branchState:s.query({select:['state']}).data.state};
writeFileSync(B+'/materials/history-data.json',JSON.stringify(data,null,2)+'\n');
writeFileSync(B+'/materials/history-data.js','const fixture = '+JSON.stringify(data)+';\n');
for(const name of ['resumed','noop','branched']) await replayScenario(prepared,JSON.parse(readFileSync(B+`/materials/${name}.scenario.json`)));
writeFileSync(B+'/evidence/fixture-checks.json',JSON.stringify({differentAmounts:true,loadedB:'再確認が必要',resumedB:'確認済み',noOpKeepsCursor:true,scenarioReplays:3,metadata:loaded.metadata},null,2)+'\n');
console.log('Fixture verified: differing amounts, B before/after seek, no-op cursor, 3 scenario replays.');
