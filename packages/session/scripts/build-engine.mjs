import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, relative } from 'node:path';
const root = resolve(import.meta.dirname, '../../..');
const paths = [];
function visit(dir) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = resolve(dir, e.name);
    if (e.isDirectory()) visit(p); else if (e.name !== 'engine-version.ts') paths.push(p);
  }
}
for (const pkg of ['ast', 'parser', 'resolver', 'runtime', 'session']) visit(resolve(root, 'packages', pkg, 'src'));
paths.push(resolve(root, 'pnpm-lock.yaml'), resolve(root, 'tsconfig.base.json'), resolve(import.meta.dirname, 'build-engine.mjs'));
const inputs = paths.map((p) => [relative(root, p), readFileSync(p, 'utf8')]).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0);
const engineVersion = createHash('sha256').update(JSON.stringify(inputs)).digest('hex');
mkdirSync(resolve(import.meta.dirname, '../dist'), { recursive: true });
writeFileSync(resolve(import.meta.dirname, '../src/engine-version.ts'), '// Generated by scripts/build-engine.mjs.\nexport const engineVersion = ' + JSON.stringify(engineVersion) + ';\n');
